# Prova nel browser delle unità con carico misto (v1.16): python3 test/browser_unita.py (server locale, porta 8766)
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome'); pg = b.new_context(viewport={'width': 430, 'height': 900}).new_page()
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8766/index.html'); pg.evaluate("localStorage.clear()"); pg.evaluate("window.print=()=>{}")
    pg.goto('http://localhost:8766/index.html?u=1993,1830,1942,1203'); pg.wait_for_timeout(1000); pg.evaluate("window.print=()=>{}")
    print('senza opzione: campi sigla', pg.locator('input[data-k=sigla]').count())
    pg.check('#cgRagg'); pg.wait_for_timeout(200); print('con opzione: campi sigla', pg.locator('input[data-k=sigla]').count())
    pg.locator('#cgLista select[data-k=unita]').nth(0).select_option('aperta'); pg.wait_for_timeout(150)
    for j in [0, 1]:
        f = pg.locator('input[data-k=sigla]').nth(j); f.fill('mscu 1234567'); f.press('Tab'); pg.wait_for_timeout(200)
    print('tipo allineato', pg.locator('#cgLista select[data-k=unita]').nth(1).input_value())
    t = pg.inner_text('#cgRis')
    print('riga 1+2', '1+2. MSCU1234567 (UN 1993, UN 1830)' in t, '| righe matrice', pg.locator('table.cgm').first.locator('tr').count() - 1)
    print('sezione unità', 'Unità di trasporto con carico misto' in t, '| esito:', t.split('→')[1].split('\n')[0].strip() if '→' in t else '?')
    print([pg.locator('table.cgm').first.locator('tr').nth(i).inner_text().replace('\t', ' ') for i in range(1, 4)])
    pg.click('#btnMerci'); pg.wait_for_timeout(200); print('matrice merci', pg.locator('table.cgm').count())
    pg.click('#btnCoppie'); pg.wait_for_timeout(200); print('dettaglio coppie di merci', pg.locator('#cgRis li:has-text("Coppie di merci")').count())
    pg.click('#btnBordo'); pg.wait_for_timeout(200); print('tabella bordo', pg.locator('table.bordo tr').count())
    pg.screenshot(path='/tmp/unita.png', full_page=True)
    f = pg.locator('input[data-k=sigla]').nth(2); f.fill('MSCU1234567 '); f.press('Tab'); pg.wait_for_timeout(200)
    t = pg.inner_text('#cgRis'); print('5.1 nella stessa unità: errore', 'non ammessa' in t, 'Non ammesso' in t)
    f = pg.locator('input[data-k=sigla]').nth(2); f.fill('X'); f.press('Tab'); pg.wait_for_timeout(200)
    pg.locator('#cgLista select[data-k=unita]').nth(3).select_option('cisterna'); pg.wait_for_timeout(150)
    f = pg.locator('input[data-k=sigla]').nth(3); f.fill('mscu 1234567'); f.press('Tab'); pg.wait_for_timeout(200)
    print('cisterna con la stessa sigla:', 'cisterne, bulk container' in pg.inner_text('#cgRis'))
    f.fill('TANK1'); f.press('Tab'); pg.wait_for_timeout(200)
    pg.click('#cgPrint'); rep = pg.inner_text('#report')
    print('REPORT', 'BAD' if ('undefined' in rep or 'NaN' in rep) else 'ok', '| unità nel report', 'unità MSCU1234567' in rep, '| matrice merci', pg.locator('#report table.cgm').count())
    pg.uncheck('#cgRagg'); pg.wait_for_timeout(200); print('opzione tolta: righe matrice', pg.locator('table.cgm').first.locator('tr').count() - 1, 'sezione', 'carico misto' in pg.inner_text('#cgRis'))
    pg.reload(); pg.wait_for_timeout(800); print('persistenza opzione', pg.is_checked('#cgRagg'))
    print('errori JS', errs)
